const PF = { map: new Map(), atlas: null, tint: new Map(), H: 9 };
(function buildPixelFont() {
  let x = 0; const list = [];
  for (const ch in PF_GLYPHS) {
    const rows = PF_GLYPHS[ch].split('/'); const w = Math.max(...rows.map(r => r.length));
    while (rows.length < 7) rows.push('.'.repeat(w));
    while (rows.length < 9) rows.push('.'.repeat(w));
    list.push({ ch, rows, w, x }); PF.map.set(ch, { x, w }); x += w + 1;
  }
  PF.map.set(' ', { x: -1, w: 3 });
  const c = document.createElement('canvas'); c.width = x; c.height = PF.H;
  const g = c.getContext('2d'); g.fillStyle = '#fff';
  for (const gl of list) gl.rows.forEach((r, y) => [...r].forEach((p, i) => { if (p === '#') g.fillRect(gl.x + i, y, 1, 1); }));
  PF.atlas = c;
})();
function pfTint(color) {
  let c = PF.tint.get(color);
  if (!c) {
    c = document.createElement('canvas'); c.width = PF.atlas.width; c.height = PF.H;
    const g = c.getContext('2d'); g.drawImage(PF.atlas, 0, 0); g.globalCompositeOperation = 'source-in'; g.fillStyle = color; g.fillRect(0, 0, c.width, c.height);
    PF.tint.set(color, c);
  }
  return c;
}
function pfGlyph(ch) { return PF.map.get(ch) || PF.map.get(ch.normalize('NFD')[0]) || PF.map.get('?'); }
function textWidth(s, scale = 1) {
  let w = 0; for (const ch of String(s)) w += pfGlyph(ch).w + 1;
  return Math.max(0, w - 1) * scale;
}
function pfRun(s, x, y, color, scale) {
  const img = pfTint(color);
  for (const ch of s) {
    const g = pfGlyph(ch);
    if (g.x >= 0) ctx.drawImage(img, g.x, 0, g.w, PF.H, x, y - 7 * scale, g.w * scale, PF.H * scale);
    x += (g.w + 1) * scale;
  }
}
// shadow: true = drop shadow, 'outline' = full dark outline, false = none
function text(s, x, y, color = '#fff', align = 'left', shadow = true, scale = 1) {
  s = String(s);
  const w = textWidth(s, scale);
  x = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x); y = Math.round(y);
  if (shadow === 'outline') { for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) pfRun(s, x + dx * scale, y + dy * scale, '#120e1c', scale); }
  else if (shadow) pfRun(s, x + scale, y + scale, '#120e1c', scale);
  pfRun(s, x, y, color, scale);
}
function wrap(s, maxW) {
  const out = []; let line = '';
  for (const w of String(s).split(' ')) {
    const t = line ? line + ' ' + w : w;
    if (textWidth(t) > maxW && line) { out.push(line); line = w; } else line = t;
  }
  if (line) out.push(line);
  return out;
}
// One frame style for every window: dark outline, a bone border, a gold rivet in each corner, and a navy field with a lighter top.
function drawPanel(x, y, w, h, opts = {}) {
  const edge = opts.edge || '#e8dcb8', field = opts.field || '#14163a', top = opts.top || '#1e2250';
  R(x, y, w, h, '#0a0812');
  R(x + 1, y + 1, w - 2, h - 2, edge);
  R(x + 2, y + 2, w - 4, h - 4, '#0a0812');
  R(x + 3, y + 3, w - 6, h - 6, field);
  R(x + 3, y + 3, w - 6, Math.min(10, h - 6), top);
  R(x + 3, y + 3, w - 6, 1, 'rgba(255,255,255,.08)');
  if (!opts.plain) for (const [cx, cy] of [[x, y], [x + w - 4, y], [x, y + h - 4], [x + w - 4, y + h - 4]]) { R(cx, cy, 4, 4, '#0a0812'); R(cx + 1, cy + 1, 2, 2, '#ffd84a'); }
}
